/**
 * Stored lessons for SHS 1 Religious and Moral Education, Art and Design
 * Studio, and Performing Arts.
 *
 * Written at about grade 9, which is inside the SHS expectation of 10 to 12.
 *
 * ── The RME rule, unchanged from JHS ─────────────────────────────────────
 *
 * Each faith is reported as its own followers state it. Nothing is ranked.
 * Where two faiths disagree the disagreement is stated plainly, because a
 * comparison that smooths a difference away is not a comparison and a
 * learner who has been given one cannot answer the question.
 *
 * What changes at SHS is the standard of the comparison. JHS asked what
 * each faith says. SHS asks where each faith says it from. So each of
 * these four lessons names the source a teaching is drawn from, and
 * teaches the shape of a comparison answer: the shared affirmation first,
 * then the particular affirmations, then what each faith does because of
 * it.
 *
 * ── The arts lessons and the examination ─────────────────────────────────
 *
 * Art and Design Studio and Performing Arts are examined on work made,
 * and that is the trap. A learner can be good at the making and still
 * fail, because the paper also asks for the reasoning: why that ground,
 * why that firing, why that tactic in the scene. So each arts lesson here
 * is built around the decision rather than the product, and says what has
 * to be written down beside the work.
 *
 * ── Equipment ────────────────────────────────────────────────────────────
 *
 * The arts are the costliest subjects in the library to equip and the
 * cheapest to fake, so these lessons say what is really needed. Painting
 * needs a ground, which can be made from a flour paste and a board.
 * Ceramics needs clay, which much of Ghana has in the ground, and a
 * firing, which can be done in a pit or a drum kiln without an electric
 * one; the lesson gives the pit method and says what a proper kiln adds.
 * The sketchbook needs paper and nothing else, and it is the single
 * highest value piece of equipment in the subject. For music, rhythm work
 * needs hands and a bell, and the notation work is paper. Dance and
 * acting need a cleared floor. Where a kiln, a piano or a stage is wanted
 * the lesson says so rather than assuming one.
 *
 * `source: 'WRITTEN'` and `approved: true` because a person wrote and read
 * every line.
 */

