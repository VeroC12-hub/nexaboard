/**
 * Stored lessons for SHS 2 English Language: summary, tone, grammar,
 * writing, speech and the set text.
 *
 * Written at about grade 9 to 10, which is inside the SHS expectation of
 * 10 to 12.
 *
 * ── The thread through all nine ──────────────────────────────────────────
 *
 * Evidence. Every one of these topics is marked on whether the learner
 * pointed at something in the text rather than said something about it.
 * A summary point must be in the passage. A tone must be carried by a
 * word you can quote. A clause must be named by the job it does in its
 * own sentence. An argument must rest on something other than its own
 * confidence. A set text answer must quote.
 *
 * So each `mechanism` here names the specific thing that has to appear on
 * the page, and names the commonest way of writing a plausible answer
 * that has no evidence in it: retelling the story, asserting the tone,
 * listing the clause types, and repeating a point louder.
 *
 * ── Ghanaian English, said plainly ───────────────────────────────────────
 *
 * Several of these lessons name spoken Ghanaian habits that the written
 * paper penalises, because a learner who is never told cannot correct
 * them. That is done without calling the spoken form wrong in itself. It
 * is a different variety, used by millions of people, and WASSCE marks a
 * written standard. The honest teaching is to say which is which and
 * when each is wanted, and that is what these lessons do.
 *
 * `source: 'WRITTEN'` and `approved: true` because a person wrote and read
 * every line.
 */

