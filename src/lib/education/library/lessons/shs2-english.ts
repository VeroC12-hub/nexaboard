    + 'and an answer without it cannot score. '
    + 'The pattern is: the tone is this, '
    + 'and these words establish it, '
    + 'because they suggest that. '
    + 'Three parts: the adjective, the quotation, the explanation. '
    + 'Learners give the first and stop. '
    + 'So the first rule is to quote. '
    + 'Not to summarise, not to refer, '
    + 'but to lift the exact words out and put them in your answer. '
