    + 'is the feeling the passage creates in the reader. '
    + 'The two are usually related and are not the same: '
    + 'a writer may use a calm tone '
    + 'to create a mood of dread. '
    + 'Attitude is the opinion the writer holds. '
    + 'Tone words are precise adjectives: '
    + 'bitter, admiring, nostalgic, mocking, indignant, '
    + 'resigned, affectionate, sarcastic, scornful, urgent, detached. '
