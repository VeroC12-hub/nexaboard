/**
 * Stored lessons for SHS 1 Elective Government.
 *
 * Written at about grade 9, which is inside the SHS expectation of 10 to 12.
 *
 * ── How this differs from Social Studies ──────────────────────────────────
 *
 * Social Studies teaches the 1992 Constitution as the arrangement Ghana
 * lives under. Government asks the prior questions: what a state is, what
 * makes a command lawful rather than merely obeyed, what a constitution is
 * for, and why a country chooses one distribution of power over another. So
 * these four lessons are largely about definitions, and that is not a
 * weakness of the subject. In Government the definition carries the marks,
 * because almost every essay turns on holding two nearby terms apart:
 * state and nation, power and authority, authority and legitimacy, a
 * constitution and constitutionalism, a unitary state and a federal one.
 *
 * ── The thread ────────────────────────────────────────────────────────────
 *
 * Each topic separates a fact from a claim of right. A state has
 * territory and a government: that is a fact. Sovereignty is the claim that
 * no outside body may overrule it. Power is the fact of being able to make
 * somebody comply. Authority is the right to. A constitution is a
 * document. Constitutionalism is the practice of actually being limited by
 * it. A learner who sees that the pairs all split the same way has the
 * subject.
 *
 * ── What has to be written down ───────────────────────────────────────────
 *
 * A Government answer is marked on structure as much as content: the
 * definition, then the distinguishing feature, then an example, then the
 * consequence. Each lesson names the example worth using, and Ghanaian
 * examples are preferred because an examiner can see whether the learner
 * knows the country.
 *
 * `source: 'WRITTEN'` and `approved: true` because a person wrote and read
 * every line.
 */

